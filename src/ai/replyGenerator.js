const MAX_LEN = 1000;

function clamp(text) {
  if (text.length <= MAX_LEN) return text;
  return text.slice(0, MAX_LEN - 3) + '...';
}

export function generateDraft({ inquiry, review }) {
  const tplFn = TEMPLATES[review?.category] || TEMPLATES['기타'];
  const draft = clamp(tplFn(inquiry.productName));
  return { draft };
}
